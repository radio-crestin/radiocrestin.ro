#!/usr/bin/env bash
# Regenerates integration_test/harness/story_media.g.dart: the story video
# the e2e fake radio server serves. Run it only to change that video.
#
# A 3 s, 180x320 H.264 (baseline) video with a quiet 440 Hz AAC track and
# its index at the front (faststart), as the admin's uploads are: short
# enough to end within a test, with sound so the radio ducks under it.
set -euo pipefail

cd "$(dirname "$0")/.."
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

ffmpeg -v error -y \
  -f lavfi -i "testsrc2=size=180x320:rate=24:duration=3" \
  -f lavfi -i "sine=frequency=440:duration=3,volume=0.02" \
  -c:v libx264 -profile:v baseline -pix_fmt yuv420p -crf 35 \
  -c:a aac -b:a 32k -ac 1 -movflags +faststart -shortest "$work/story.mp4"

{
  echo "// GENERATED by integration_test/tool/generate_story_media.sh. DO NOT EDIT."
  echo "// ignore_for_file: lines_longer_than_80_chars"
  echo
  printf "const String storyVideoMp4Base64 =\n    '%s';\n" \
    "$(base64 < "$work/story.mp4" | tr -d '\r\n')"
} > harness/story_media.g.dart

echo "Wrote integration_test/harness/story_media.g.dart"
